#include <stdio.h>  // header file 


int main(){

    printf("Hello world \n");

    // variables, data types 


    // 1 gb => 1024 mb 
    // 1 mb => 1024 kb
    // 1kb => 1024 byte 
    // 1 byte => 8 bit 
    // 1 bit => either 0 or 1

    int a = 10;  // => 4 bytes 

    float b= 20;

    double d = 30;

    char c = 'F';
    int r;  // int default = > 0 

    
    printf("%d \n" , r);

    printf("%d \n" , a);

    printf("%.2f \n" , b);

    printf("%Lf \n" , d);

    printf("%c \n" , c);




   
    return 0;
}
